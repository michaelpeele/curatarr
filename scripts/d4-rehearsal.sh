#!/usr/bin/env bash
# D4 scratch rehearsal: isolated blue/green slots plus host edge proxy.
# Uses scratch env/state under state/rehearsal and the sandbox DB as snapshot source.
# Never starts or reconfigures production.
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

SCRATCH="$ROOT/state/rehearsal"
BLUE_ENV="$SCRATCH/blue.env"
GREEN_ENV="$SCRATCH/green.env"
EDGE_ENV="$SCRATCH/edge.env"
TEMPLATE="$SCRATCH/Caddyfile.template"
SLOT_COMPOSE="$ROOT/docker-compose.slot.yml"
EDGE_COMPOSE="$ROOT/docker-compose.edge.yml"
SNAPSHOT_SOURCE_VOLUME=curatarr-sandbox-data
PUBLIC_URL=http://localhost:51573

export_env() {
  export BLUE_ENV_FILE="$BLUE_ENV"
  export GREEN_ENV_FILE="$GREEN_ENV"
  export EDGE_ENV_FILE="$EDGE_ENV"
  export EDGE_TEMPLATE_FILE="$TEMPLATE"
  export EDGE_STATE_DIR="$SCRATCH"
}

usage() {
  cat <<'EOF'
Usage: scripts/d4-rehearsal.sh <command>

Commands:
  prepare   Write scratch env files and directories under state/rehearsal.
  snapshot  Copy the sandbox DB and data-protection-keys into state/rehearsal.
  up        Prepare, snapshot, seed both slot volumes, start blue/green and edge.
  status    Run promote.sh --status against the scratch stack.
  down      Stop and remove scratch slot/edge containers and volumes.

Scratch inputs are isolated from production:
  env/state: state/rehearsal/
  DB source: curatarr-sandbox-data (never curatarr-data)
  public URL: http://localhost:51573
EOF
}

prepare() {
  mkdir -p "$SCRATCH"/{media,blue-output,green-output,blue-vlibs,green-vlibs,data-protection-keys}
  docker run --rm -v "$SCRATCH:/scratch" python:3.11-slim sh -c \
    'chown -R 1654:1654 /scratch/blue-output /scratch/green-output /scratch/blue-vlibs /scratch/green-vlibs'
  cp "$ROOT/configs/Caddyfile.template" "$TEMPLATE"

  cat > "$BLUE_ENV" <<EOF
# D4 scratch blue slot. Generated by scripts/d4-rehearsal.sh.
APP_NAME=curatarr-scratch-blue
APP_NAME_PASCAL=Curatarr
SLOT_NAME=blue
CURATARR_RELEASE_TAG=1.0.0
HOST_MEDIA_DIR=$SCRATCH/media
HOST_OUTPUT_DIR=$SCRATCH/blue-output
HOST_VIRTUAL_LIBS_DIR=$SCRATCH/blue-vlibs
API_LOCAL_PORT=15100
WEB_LOCAL_PORT=15173
FRONTEND_BASE_URL=$PUBLIC_URL
COOKIE_NAME=curatarr.auth
TMDB_KEY=
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASSWORD=
SMTP_FROM=
EOF

  cat > "$GREEN_ENV" <<EOF
# D4 scratch green slot. Generated by scripts/d4-rehearsal.sh.
APP_NAME=curatarr-scratch-green
APP_NAME_PASCAL=Curatarr
SLOT_NAME=green
CURATARR_RELEASE_TAG=1.0.0
HOST_MEDIA_DIR=$SCRATCH/media
HOST_OUTPUT_DIR=$SCRATCH/green-output
HOST_VIRTUAL_LIBS_DIR=$SCRATCH/green-vlibs
API_LOCAL_PORT=15200
WEB_LOCAL_PORT=15273
FRONTEND_BASE_URL=$PUBLIC_URL
COOKIE_NAME=curatarr.auth
TMDB_KEY=
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASSWORD=
SMTP_FROM=
EOF

  cat > "$EDGE_ENV" <<EOF
# D4 scratch edge proxy. Generated by scripts/d4-rehearsal.sh.
CURATARR_DOMAIN=$PUBLIC_URL
BLUE_WEB_PORT=15173
GREEN_WEB_PORT=15273
ACTIVE_SLOT=blue
CADDY_ADMIN=localhost:2019
SMTP_FROM=
EDGE_TEMPLATE_FILE=$TEMPLATE
EDGE_STATE_DIR=$SCRATCH
EOF

  export_env
}

snapshot() {
  prepare
  echo "Snapshotting $SNAPSHOT_SOURCE_VOLUME into $SCRATCH/curatarr.db..."
  docker run --rm \
    -v "$SNAPSHOT_SOURCE_VOLUME:/data:ro" \
    -v "$SCRATCH:/backup" \
    python:3.11-slim python3 -c \
    'import sqlite3; s=sqlite3.connect("file:/data/curatarr.db?mode=ro", uri=True); d=sqlite3.connect("/backup/curatarr.db"); s.backup(d); s.close(); d.close()'

  docker run --rm \
    -v "$SCRATCH:/backup" \
    python:3.11-slim sh -c \
    'rm -rf /backup/data-protection-keys && mkdir -p /backup/data-protection-keys'
  docker run --rm \
    -v "$SNAPSHOT_SOURCE_VOLUME:/data:ro" \
    -v "$SCRATCH/data-protection-keys:/keys" \
    python:3.11-slim sh -c \
    'mkdir -p /keys && cp -a /data/data-protection-keys/. /keys/ && chown -R 1654:1654 /keys'
  echo "Snapshot complete."
}

restore_into_slot() { # restore_into_slot <blue|green>
  local slot="$1"
  local vol="curatarr-$slot-data"
  docker volume create "$vol" >/dev/null
  docker run --rm \
    -v "$vol:/data" \
    -v "$SCRATCH/curatarr.db:/backup/curatarr.db:ro" \
    python:3.11-slim sh -c \
    'cp /backup/curatarr.db /data/curatarr.db && rm -f /data/curatarr.db-wal /data/curatarr.db-shm && chown -R 1654:1654 /data'
  docker run --rm \
    -v "$vol:/data" \
    -v "$SCRATCH/data-protection-keys:/keys:ro" \
    python:3.11-slim sh -c \
    'mkdir -p /data/data-protection-keys && cp -a /keys/. /data/data-protection-keys/ && chown -R 1654:1654 /data'
  echo "Seeded slot $slot from scratch snapshot."
}

up() {
  prepare
  snapshot
  printf 'blue' > "$SCRATCH/active-slot"
  restore_into_slot blue
  restore_into_slot green

  OUTPUT_MOUNT_MODE=rw docker compose -f "$SLOT_COMPOSE" --env-file "$BLUE_ENV" \
    up -d --force-recreate --no-build api web
  OUTPUT_MOUNT_MODE=ro docker compose -f "$SLOT_COMPOSE" --env-file "$GREEN_ENV" \
    up -d --force-recreate --no-build api web
  docker compose -f "$EDGE_COMPOSE" --env-file "$EDGE_ENV" \
    up -d --force-recreate --no-build edge
  echo "Scratch stack up. Public URL: $PUBLIC_URL"
}

down() {
  prepare
  docker compose -f "$EDGE_COMPOSE" --env-file "$EDGE_ENV" down -v --remove-orphans || true
  docker compose -f "$SLOT_COMPOSE" --env-file "$BLUE_ENV" down -v --remove-orphans || true
  docker compose -f "$SLOT_COMPOSE" --env-file "$GREEN_ENV" down -v --remove-orphans || true
  echo "Scratch stack down."
}

status() {
  prepare
  "$ROOT/scripts/promote.sh" --status
}

case "${1:-}" in
  prepare) prepare ;;
  snapshot) snapshot ;;
  up) up ;;
  down) down ;;
  status) status ;;
  -h|--help|help|*) usage ;;
esac

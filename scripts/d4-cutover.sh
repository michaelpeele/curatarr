#!/usr/bin/env bash
# D4 production cutover: blue/green slots plus host edge proxy.
# Keeps the public Tailscale hostname and writes all generated state to state/cutover.
# Rollback requires an explicit separate command; this script never rolls back.
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

CUTOVER="$ROOT/state/cutover"
BLUE_ENV="$CUTOVER/blue.env"
GREEN_ENV="$CUTOVER/green.env"
EDGE_ENV="$CUTOVER/edge.env"
TEMPLATE="$CUTOVER/Caddyfile.template"
SNAPSHOT_DB="$CUTOVER/curatarr.db"
SNAPSHOT_KEYS="$CUTOVER/data-protection-keys"
SLOT_COMPOSE="$ROOT/docker-compose.slot.yml"
EDGE_COMPOSE="$ROOT/docker-compose.edge.yml"
PUBLIC_URL="https://curatarr.tail0307d.ts.net"
EDGE_TARGET="http://172.22.0.1:5180"
OLD_TARGET="http://127.0.0.1:80"
SOURCE_VOLUME="curatarr-data"

export_env() {
  export BLUE_ENV_FILE="$BLUE_ENV"
  export GREEN_ENV_FILE="$GREEN_ENV"
  export EDGE_ENV_FILE="$EDGE_ENV"
  export EDGE_TEMPLATE_FILE="$TEMPLATE"
  export EDGE_STATE_DIR="$CUTOVER"
  export BACKUP_DB="$SNAPSHOT_DB"
  export BACKUP_KEYS_DIR="$SNAPSHOT_KEYS"
}

usage() {
  cat <<'EOF'
Usage: scripts/d4-cutover.sh <command>

Commands:
  prepare   Write production env files and directories under state/cutover.
  snapshot  Freeze prod API writes, snapshot curatarr-data into state/cutover,
            copy data-protection-keys, verify DB, then restart prod API.
  up        Seed blue/green volumes from the prod snapshot and start both slots.
            Blue starts rw; green starts ro. Edge routing is unchanged.
  route     Start the host edge proxy on :5180 and repoint Tailscale Serve to it.
            Public hostname stays https://curatarr.tail0307d.ts.net.
  verify    Verify public login, API, hubs, invite/reset routes, and output modes.
  flip      Run promote.sh --flip --confirm-cutover after verification.
  finish    Stop the old prod api/web services after the verified flip.
  status    Run promote.sh --status against the production slots.
  abort     Restore the old Tailscale target and stop slots/edge; start old api/web.
            Only use before an approved flip.

Generated env/state is ignored via state/.
Rollback after a flip requires an explicit separate instruction.
EOF
}

load_repo_env() {
  set -a
  # shellcheck disable=SC1091
  . "$ROOT/.env"
  set +a
}

prepare() {
  mkdir -p "$CUTOVER"
  load_repo_env
  cp "$ROOT/configs/Caddyfile.template" "$TEMPLATE"

  cat > "$BLUE_ENV" <<EOF
# D4 production blue slot. Generated by scripts/d4-cutover.sh.
APP_NAME=$APP_NAME
APP_NAME_PASCAL=$APP_NAME_PASCAL
SLOT_NAME=blue
CURATARR_RELEASE_TAG=1.0.0
HOST_MEDIA_DIR=$HOST_MEDIA_DIR
HOST_OUTPUT_DIR=$HOST_OUTPUT_DIR
HOST_VIRTUAL_LIBS_DIR=$HOST_VIRTUAL_LIBS_DIR
API_LOCAL_PORT=15100
WEB_LOCAL_PORT=15173
FRONTEND_BASE_URL=$PUBLIC_URL
COOKIE_NAME=curatarr.auth
TMDB_KEY=${TMDB_KEY:-}
SMTP_HOST=${SMTP_HOST:-}
SMTP_PORT=${SMTP_PORT:-587}
SMTP_USER=${SMTP_USER:-}
SMTP_PASSWORD=${SMTP_PASSWORD:-}
SMTP_FROM=${SMTP_FROM:-}
EOF

  cat > "$GREEN_ENV" <<EOF
# D4 production green slot. Generated by scripts/d4-cutover.sh.
APP_NAME=$APP_NAME
APP_NAME_PASCAL=$APP_NAME_PASCAL
SLOT_NAME=green
CURATARR_RELEASE_TAG=1.0.0
HOST_MEDIA_DIR=$HOST_MEDIA_DIR
HOST_OUTPUT_DIR=$HOST_OUTPUT_DIR
HOST_VIRTUAL_LIBS_DIR=$HOST_VIRTUAL_LIBS_DIR
API_LOCAL_PORT=15200
WEB_LOCAL_PORT=15273
FRONTEND_BASE_URL=$PUBLIC_URL
COOKIE_NAME=curatarr.auth
TMDB_KEY=${TMDB_KEY:-}
SMTP_HOST=${SMTP_HOST:-}
SMTP_PORT=${SMTP_PORT:-587}
SMTP_USER=${SMTP_USER:-}
SMTP_PASSWORD=${SMTP_PASSWORD:-}
SMTP_FROM=${SMTP_FROM:-}
EOF

  cat > "$EDGE_ENV" <<EOF
# D4 production edge proxy. Generated by scripts/d4-cutover.sh.
CURATARR_DOMAIN=:5180
BLUE_WEB_PORT=15173
GREEN_WEB_PORT=15273
ACTIVE_SLOT=blue
CADDY_ADMIN=localhost:2019
SMTP_FROM=${SMTP_FROM:-}
EDGE_TEMPLATE_FILE=$TEMPLATE
EDGE_STATE_DIR=$CUTOVER
EOF

  chmod 600 "$BLUE_ENV" "$GREEN_ENV" "$EDGE_ENV"
  [[ -f "$CUTOVER/active-slot" ]] || printf 'blue' > "$CUTOVER/active-slot"

  # Compose gives shell env precedence over --env-file. load_repo_env exported
  # prod values here; keep them out of slot Compose and promote.sh children.
  unset API_LOCAL_PORT WEB_LOCAL_PORT HOST_OUTPUT_DIR HOST_VIRTUAL_LIBS_DIR HOST_MEDIA_DIR
  unset FRONTEND_BASE_URL COOKIE_NAME CURATARR_RELEASE_TAG TMDB_KEY APP_NAME APP_NAME_PASCAL
  unset SMTP_HOST SMTP_PORT SMTP_USER SMTP_PASSWORD SMTP_FROM TS_AUTHKEY TS_EXTRA_ARGS
  export_env
}

require_snapshot() {
  [[ -f "$SNAPSHOT_DB" ]] || { echo "Missing $SNAPSHOT_DB; run snapshot first." >&2; exit 1; }
  [[ -d "$SNAPSHOT_KEYS" ]] || { echo "Missing $SNAPSHOT_KEYS; run snapshot first." >&2; exit 1; }
}

verify_snapshot() {
  docker run --rm \
    -v "$SNAPSHOT_DB:/data/curatarr.db:ro" \
    python:3.11-slim python3 -c \
    'import sqlite3; c=sqlite3.connect("file:/data/curatarr.db?mode=ro", uri=True); print("integrity="+c.execute("PRAGMA integrity_check").fetchone()[0]); print("users="+str(c.execute("select count(*) from AspNetUsers").fetchone()[0])); print("libraries="+str(c.execute("select count(*) from VirtualLibraries").fetchone()[0])); print("items="+str(c.execute("select count(*) from SourceItems").fetchone()[0]))'
}

snapshot() {
  prepare
  trap 'docker compose start api >/dev/null 2>&1 || true' EXIT

  echo "Write freeze: stopping prod api..."
  docker compose stop api >/dev/null

  rm -f "$SNAPSHOT_DB" "$SNAPSHOT_DB-shm" "$SNAPSHOT_DB-wal"
  echo "Backing up production SQLite database..."
  # Prod API is stopped, so SQLite needs a writable mount to recreate WAL/SHM.
  docker run --rm \
    -v "$SOURCE_VOLUME:/data" \
    -v "$CUTOVER:/backup" \
    python:3.11-slim python3 -c \
    'import sqlite3; s=sqlite3.connect("file:/data/curatarr.db?mode=ro", uri=True); d=sqlite3.connect("/backup/curatarr.db"); s.backup(d); d.execute("PRAGMA journal_mode=DELETE"); d.commit(); print("backup ok journal_mode="+d.execute("PRAGMA journal_mode").fetchone()[0]); s.close(); d.close()'

  docker run --rm \
    -v "$CUTOVER:/backup" \
    python:3.11-slim sh -c \
    'rm -rf /backup/data-protection-keys && mkdir -p /backup/data-protection-keys'
  docker run --rm \
    -v "$SOURCE_VOLUME:/data:ro" \
    -v "$SNAPSHOT_KEYS:/keys" \
    python:3.11-slim sh -c \
    'mkdir -p /keys && cp -a /data/data-protection-keys/. /keys/ && chown -R 1654:1654 /keys'

  verify_snapshot | tee "$CUTOVER/snapshot-check.txt"
  echo "Snapshot complete."

  docker compose start api >/dev/null
  trap - EXIT
  echo "Prod api restarted."
}

restore_into_slot() { # restore_into_slot <blue|green>
  local slot="$1"
  local vol="curatarr-$slot-data"
  docker volume create "$vol" >/dev/null
  docker run --rm \
    -v "$vol:/data" \
    -v "$SNAPSHOT_DB:/backup/curatarr.db:ro" \
    python:3.11-slim sh -c \
    'cp /backup/curatarr.db /data/curatarr.db && rm -f /data/curatarr.db-wal /data/curatarr.db-shm && chown -R 1654:1654 /data'
  docker run --rm \
    -v "$vol:/data" \
    -v "$SNAPSHOT_KEYS:/keys:ro" \
    python:3.11-slim sh -c \
    'mkdir -p /data/data-protection-keys && cp -a /keys/. /data/data-protection-keys/ && chown -R 1654:1654 /data'
  echo "Seeded slot $slot from production snapshot."
}

wait_url() { # wait_url <url> <label>
  local url="$1" label="$2" code=""
  for _ in $(seq 1 60); do
    code=$(curl -s -o /dev/null -w '%{http_code}' "$url" || true)
    [[ "$code" == "200" ]] && return 0
    sleep 2
  done
  echo "$label did not become ready ($url returned ${code:-no response})" >&2
  return 1
}

up() {
  prepare
  require_snapshot
  printf 'blue' > "$CUTOVER/active-slot"
  restore_into_slot blue
  restore_into_slot green

  OUTPUT_MOUNT_MODE=rw docker compose -f "$SLOT_COMPOSE" --env-file "$BLUE_ENV" \
    up -d --force-recreate --no-build api web
  OUTPUT_MOUNT_MODE=ro docker compose -f "$SLOT_COMPOSE" --env-file "$GREEN_ENV" \
    up -d --force-recreate --no-build api web
  wait_url http://127.0.0.1:15100/api/bootstrapped "blue API"
  wait_url http://127.0.0.1:15173/api/bootstrapped "blue web"
  wait_url http://127.0.0.1:15200/api/bootstrapped "green API"
  wait_url http://127.0.0.1:15273/api/bootstrapped "green web"
  echo "Production slots up. Blue rw; green ro. Edge routing unchanged."
}

route() {
  prepare
  docker compose -f "$EDGE_COMPOSE" --env-file "$EDGE_ENV" \
    up -d --force-recreate --no-build edge
  wait_url http://127.0.0.1:5180/api/bootstrapped "edge :5180"
  docker exec ts-curatarr sh -c \
    'wget -q -O /dev/null http://172.22.0.1:5180/api/bootstrapped'
  docker exec ts-curatarr tailscale serve --bg --https=443 --yes "$EDGE_TARGET" >/dev/null
  docker exec ts-curatarr tailscale serve status
  wait_url "$PUBLIC_URL/api/bootstrapped" "public URL"
  echo "Tailscale route now targets $EDGE_TARGET; public hostname unchanged."
}

verify() {
  prepare
  local jar status_code hub
  jar=$(mktemp)
  trap 'rm -f "$jar"' RETURN

  wait_url "$PUBLIC_URL/api/bootstrapped" "public URL"

  status_code=$(curl -s -o /dev/null -w '%{http_code}' -c "$jar" \
    -H 'Content-Type: application/json' \
    -d "{\"email\":\"${ADMIN_EMAIL:-michael.peele@gmail.com}\",\"password\":\"${ADMIN_PASSWORD:-Passw0rd!123}\"}" \
    "$PUBLIC_URL/api/auth/login")
  [[ "$status_code" == "200" ]] || { echo "public login failed (HTTP $status_code)" >&2; return 1; }

  for path in /api/source-items /api/virtual-libraries /api/me; do
    status_code=$(curl -s -o /dev/null -w '%{http_code}' -b "$jar" "$PUBLIC_URL$path")
    [[ "$status_code" == "200" ]] || { echo "public $path failed (HTTP $status_code)" >&2; return 1; }
  done

  for hub in /hubs/scan /hubs/activity /hubs/logs; do
    status_code=$(curl -s -o /dev/null -w '%{http_code}' -b "$jar" -X POST \
      -H 'Content-Type: application/json' \
      "$PUBLIC_URL$hub/negotiate?negotiateVersion=1")
    [[ "$status_code" == "200" ]] || { echo "public $hub negotiate failed (HTTP $status_code)" >&2; return 1; }
  done

  for path in "/accept-invite?token=d4-test" "/reset-password?token=d4-test"; do
    status_code=$(curl -s -o /dev/null -w '%{http_code}' "$PUBLIC_URL$path")
    [[ "$status_code" == "200" ]] || { echo "public SPA $path failed (HTTP $status_code)" >&2; return 1; }
  done

  local active standby
  active=$("$ROOT/scripts/edge.sh" status | sed -n 's/^active_slot=//p')
  case "$active" in
    blue) standby=green ;;
    green) standby=blue ;;
    *) echo "Invalid active slot: $active" >&2; return 1 ;;
  esac

  docker exec "curatarr-$active-api" sh -c 'touch /output/.d4-cutover-write-test && rm -f /output/.d4-cutover-write-test'
  if docker exec "curatarr-$standby-api" sh -c 'touch /output/.d4-cutover-write-test' 2>/dev/null; then
    docker exec "curatarr-$standby-api" sh -c 'rm -f /output/.d4-cutover-write-test' || true
    echo "standby slot $standby output is writable; expected read-only" >&2
    return 1
  fi

  echo "Public verification PASSED. active=$active standby=$standby; active writable, standby read-only."
}

flip() {
  prepare
  require_snapshot
  "$ROOT/scripts/promote.sh" --flip --confirm-cutover
  wait_url "$PUBLIC_URL/api/bootstrapped" "public URL after flip"
}

finish() {
  prepare
  docker compose stop api web >/dev/null
  wait_url "$PUBLIC_URL/api/bootstrapped" "public URL after old stack stop"
  echo "Old prod api/web stopped. Slots and edge serve the public hostname."
}

status() {
  prepare
  "$ROOT/scripts/promote.sh" --status
}

abort() {
  prepare
  docker exec ts-curatarr tailscale serve --bg --https=443 --yes "$OLD_TARGET" >/dev/null
  docker compose -f "$EDGE_COMPOSE" --env-file "$EDGE_ENV" down -v --remove-orphans || true
  docker compose -f "$SLOT_COMPOSE" --env-file "$GREEN_ENV" down -v --remove-orphans || true
  docker compose -f "$SLOT_COMPOSE" --env-file "$BLUE_ENV" down -v --remove-orphans || true
  docker compose start api web >/dev/null
  wait_url "$PUBLIC_URL/api/bootstrapped" "old prod stack"
  docker exec ts-curatarr tailscale serve status
  echo "Aborted: old prod stack restored."
}

case "${1:-}" in
  prepare) prepare ;;
  snapshot) snapshot ;;
  up) up ;;
  route) route ;;
  verify) verify ;;
  flip) flip ;;
  finish) finish ;;
  status) status ;;
  abort) abort ;;
  -h|--help|help|*) usage ;;
esac
